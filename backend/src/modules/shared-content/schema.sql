CREATE TABLE IF NOT EXISTS content_entries (
 kind VARCHAR(32) NOT NULL, entity_id VARCHAR(64) NOT NULL,
 revision BIGINT UNSIGNED NOT NULL DEFAULT 1, published_revision BIGINT UNSIGNED NULL,
 state ENUM('draft','published','withdrawn','deleted') NOT NULL DEFAULT 'draft',
 hash CHAR(64) NOT NULL, updated_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
 PRIMARY KEY(kind,entity_id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS content_revisions (
 kind VARCHAR(32) NOT NULL, entity_id VARCHAR(64) NOT NULL, revision BIGINT UNSIGNED NOT NULL,
 payload JSON NOT NULL, hash CHAR(64) NOT NULL, actor_id VARCHAR(64) NULL,
 created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3), PRIMARY KEY(kind,entity_id,revision)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS content_audit (
 id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY, kind VARCHAR(32), entity_id VARCHAR(64),
 revision BIGINT UNSIGNED, action VARCHAR(48) NOT NULL, actor_id VARCHAR(64),
 request_id VARCHAR(128), details JSON, created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS content_outbox (
 id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY, kind VARCHAR(32) NOT NULL,entity_id VARCHAR(64) NOT NULL,
 revision BIGINT UNSIGNED NOT NULL, action VARCHAR(32) NOT NULL,payload JSON,
 attempts INT NOT NULL DEFAULT 0,last_error VARCHAR(300),created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
 delivered_at DATETIME(3), KEY pending(delivered_at,id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS content_delivery_receipts (
 site_id VARCHAR(16) NOT NULL,kind VARCHAR(32) NOT NULL,entity_id VARCHAR(64) NOT NULL,revision BIGINT UNSIGNED NOT NULL,
 state VARCHAR(32) NOT NULL,http_status INT NULL,verified_at DATETIME(3) NOT NULL,
 PRIMARY KEY(site_id,kind,entity_id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS content_idempotency (
 request_key VARCHAR(128) NOT NULL PRIMARY KEY,request_hash CHAR(64) NOT NULL,
 status_code INT, response JSON,created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS content_legacy_map (
 source_site VARCHAR(16) NOT NULL,kind VARCHAR(32) NOT NULL,source_id VARCHAR(64) NOT NULL,
 entity_id VARCHAR(64) NOT NULL,source_hash CHAR(64) NOT NULL,decision JSON,
 PRIMARY KEY(source_site,kind,source_id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS content_url_aliases (
 site_id VARCHAR(16) NOT NULL,kind VARCHAR(32) NOT NULL,locale VARCHAR(8) NOT NULL,slug VARCHAR(255) NOT NULL,
 entity_id VARCHAR(64) NOT NULL,PRIMARY KEY(site_id,kind,locale,slug)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS content_site_profiles (
 site_id VARCHAR(16) NOT NULL PRIMARY KEY,profile JSON NOT NULL,updated_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS content_offers (
 site_id VARCHAR(16) NOT NULL,kind VARCHAR(32) NOT NULL,entity_id VARCHAR(64) NOT NULL,
 offer JSON NOT NULL,updated_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),PRIMARY KEY(site_id,kind,entity_id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS content_translation_states (
 kind VARCHAR(32) NOT NULL,entity_id VARCHAR(64) NOT NULL,locale VARCHAR(8) NOT NULL,
 source_revision BIGINT UNSIGNED NOT NULL,status ENUM('draft','review_required','approved') NOT NULL,
 PRIMARY KEY(kind,entity_id,locale)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS content_preview_sessions (
 token_hash CHAR(64) NOT NULL PRIMARY KEY, site_id VARCHAR(16) NOT NULL,kind VARCHAR(32) NOT NULL,
 entity_id VARCHAR(64) NOT NULL,locale VARCHAR(8) NOT NULL,actor_id VARCHAR(64),expires_at DATETIME(3) NOT NULL,
 created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),KEY expiration(expires_at)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS content_migrations (
 name VARCHAR(64) NOT NULL PRIMARY KEY,fingerprint CHAR(64) NOT NULL,applied_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
