    const featured = mapped(urls[0], imageMap);

    serviceRows.push([id, serviceType(detail), index < 6 ? 1 : 0, 1, index + 1, price.toFixed(2), 'TRY', 0, featured, featured, BASE_DATE, BASE_DATE]);

