function assetId(namespace, index, imageIndex = 0) {
  return `${namespace}-0000-4000-8000-${String(index + 1).padStart(6, '0')}${String(imageIndex + 1).padStart(6, '0')}`;
}

function mapped(url, imageMap) {
  return imageMap[url] ?? url ?? null;
}

function packageFeatures(pkg) {
  return (pkg?.options ?? []).map((option) => {
    const suffix = option.selectboxHelpText ? String(option.selectboxHelpText) : '';
    if (option.value === true) return option.title;
    if (option.value === false || option.value === null || option.value === undefined) return `${option.title}: Yok`;
    return `${option.title}: ${option.value}${suffix}`;
  }).filter(Boolean);
}

function normalizedPackage(pkg, multiplier) {
  const price = Number(pkg?.price ?? 0) * multiplier;
  return {
    title: pkg?.title ?? '',
    price,
    currency: 'TRY',
    duration_days: pkg?.duration ?? null,
    revisions: pkg?.revisions ?? null,
    description: pkg?.description ?? null,
    options: (pkg?.options ?? []).map((option) => ({
      title: option.title ?? '',
      value: option.value ?? false,
      unit: option.selectboxHelpText ?? null,
    })),
  };
}

function serviceType(detail) {
  const slug = `${detail?.gig_category?.slug ?? ''} ${detail?.gig_category_sub?.slug ?? ''}`;
  if (/e-?ticaret|video|tasarim|sosyal|seo|web/.test(slug)) return 'other';
  if (/server|teknoloji|yazilim/.test(slug)) return 'engineering_support';
  return 'other';
}

