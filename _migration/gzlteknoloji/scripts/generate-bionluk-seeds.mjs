import fs from 'node:fs';
import path from 'node:path';

const ROOT = path.resolve(import.meta.dirname, '..');
const DOCS = path.join(ROOT, 'docs/bionluk');
const SQL_DIR = path.join(ROOT, 'backend/src/db/seed/sql');
