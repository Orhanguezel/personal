function generateSlugRedirects(gigs, overrides) {
  const redirects = {};
  gigs.forEach((item) => {
    const detail = item.detail ?? {};
    const gigId = String(detail.gig_id ?? item.list_item?.id ?? '');
    const override = overrides.gigs?.[gigId] ?? {};
    const titleTr = override.title_tr ?? detail.title ?? item.list_item?.title ?? '';
    const titleEn = override.title_en ?? `I provide ${titleTr}`;
    const oldTr = slugify(detail.slug ?? titleTr);
    const oldEn = slugify(titleEn);
    const newTr = slugify(override.slug?.tr ?? override.slug_tr ?? oldTr);
    const newEn = slugify(override.slug?.en ?? override.slug_en ?? oldEn);
    if (oldTr !== newTr) redirects[oldTr] = newTr;
    if (oldEn !== newEn) redirects[oldEn] = newEn;
  });
  return redirects;
}

